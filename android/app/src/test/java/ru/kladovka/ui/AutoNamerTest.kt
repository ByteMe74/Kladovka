package ru.kladovka.ui

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Автонумерация имён.
 *
 * Функция решает задачу, где ошибка незаметна: если выдать занятое имя, в
 * интерфейсе появятся две одинаковые «Полка 5», и человек не сможет их
 * различить. Поэтому проверяем не только «следующий по порядку», но и то, что
 * номер не переиспользуется после удаления записей.
 */
class AutoNamerTest {

    @Test
    fun `пустой список даёт первый номер`() {
        assertEquals("Полка 1", nextAutoName(emptyList(), "Полка"))
        assertEquals("Вещь 1", nextAutoName(emptyList(), "Вещь"))
    }

    @Test
    fun `берётся следующий после максимального`() {
        val existing = listOf("Полка 1", "Полка 2", "Полка 3")
        assertEquals("Полка 4", nextAutoName(existing, "Полка"))
    }

    @Test
    fun `пропуски в нумерации не сбивают`() {
        // Удалили «Полка 2» и «Полка 3». Нельзя выдать «Полка 2» — человек бы
        // решил, что это та же полка, что была.
        val existing = listOf("Полка 1", "Полка 4")
        assertEquals("Полка 5", nextAutoName(existing, "Полка"))
    }

    @Test
    fun `одноцифровые и двухцифровые номера сравниваются как числа`() {
        // Строковое сравнение перепутало бы "9" и "10": "9" больше "10".
        val existing = listOf("Полка 9")
        assertEquals("Полка 10", nextAutoName(existing, "Полка"))
        val many = listOf("Полка 9", "Полка 10", "Полка 11")
        assertEquals("Полка 12", nextAutoName(many, "Полка"))
    }

    @Test
    fun `чужие имена не влияют`() {
        val existing = listOf("Стеллаж 1", "Стеллаж 7", "Контейнер 3")
        // Ни одного «Полка N» — начинаем с единицы, а не считаем чужие номера.
        assertEquals("Полка 1", nextAutoName(existing, "Полка"))
    }

    @Test
    fun `регистр и пробелы не мешают узнать свой номер`() {
        val existing = listOf("полка 1", "ПОЛКА 2", " Полка 3 ")
        assertEquals("Полка 4", nextAutoName(existing, "Полка"))
    }

    @Test
    fun `имя с буквами после номера своим не считается`() {
        // «Полка 5 (новый)» — это ручное имя, не автонумерация. Считать его
        // номером нельзя: иначе после его удаления номер 5 уйдёт в пустоту
        // либо, что хуже, будет переиспользован под другую полку.
        val existing = listOf("Полка 1", "Полка 5 (новый)")
        assertEquals("Полка 2", nextAutoName(existing, "Полка"))
    }

    @Test
    fun `префикс с пробелом внутри экранируется`() {
        // Префикс может содержать пробел, и он должен пониматься буквально.
        // Пробелов на конце быть не должно: разделитель функция ставит сама
        // («$prefix $n»), поэтому хвостовой пробел дал бы «Контейнер  1».
        // Так и вызывается на самом деле — пять мест зовут nextAutoName с
        // голым словом без пробела.
        assertEquals("Ночной стеллаж 1", nextAutoName(emptyList(), "Ночной стеллаж"))
        assertEquals(
            "Ночной стеллаж 4",
            nextAutoName(listOf("Ночной стеллаж 1", "Ночной стеллаж 3"), "Ночной стеллаж")
        )
    }

    @Test
    fun `спецсимвол в префиксе не ломает регулярку`() {
        // Если префикс не экранировать, «Полка (1)» превратит скобку в группу
        // и совпадёт с не тем именем.
        val prefix = "Полка (1)"
        assertEquals("$prefix 1", nextAutoName(emptyList(), prefix))
        assertEquals(
            "$prefix 4",
            nextAutoName(listOf("$prefix 1", "$prefix 3"), prefix)
        )
    }
}