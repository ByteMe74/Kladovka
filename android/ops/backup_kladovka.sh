#!/bin/bash
# Кладовка: резервное копирование SQLite и фотографий.
#
# Запуск по крону: 30 3 * * * /www/server/kladovka-config/backup_kladovka.sh
#
# Почему фотографии здесь же, а не отдельным скриптом: в базе лежат только
# ссылки на файлы, сами картинки — в /photos рядом. Копия базы без них даёт
# вещи без фотографий, и человек обнаруживает это только тогда, когда
# восстанавливается. Ставятся в один архив по одному таймстемпу, поэтому
# база и фотографии внутри всегда одной свежести — восстановить можно
# согласованный кусок, а не «базу от сегодня и фото от позавчера».
#
# Склейка в один .tar.gz, а не отдельные копии каждого: держать их согласованными
# иначе нельзя, а каталог /photos может разойтись с базой в любую сторону.
set -euo pipefail

DB=/www/wwwroot/kladovka.dr6ter.ru/data/kladovka.db
PHOTOS=/www/wwwroot/kladovka.dr6ter.ru/photos
DEST=/www/server/kladovka-config/backups
LOG="$DEST/backup.log"

# Витрина для копий, которые уходят с машины.
#
# Пока бэкапы лежат только здесь, потеря сервера — это потеря копий: восстанавливать
# будет нечем. Наружу они уходят с машины владельца, где есть доступ к Nextcloud,
# и в облако попадают уже оттуда. Схема именно такая потому, что пароль от
# Nextcloud на сервер класть нельзя.
#
# С каталога бэкапов scp не заберёт ничего: родитель
# `/www/server/kladovka-config` закрыт (`drwxr-x---`), пройти внутрь без sudo
# нельзя. Ослаблять права на каталог с данными не будем — тогда к бэкапам
# получил бы доступ любой, у кого есть шелл на этой машине. Поэтому сюда
# выкладывается ровно одна копия, уже проверенная, с правами на пользователя:
# читает её только владелец и только то, что скрипт сам выложил.
STAGE=/home/dash/kladovka-offsite
KEEP_DAYS=30
THRESHOLD=1   # строк в items; меньше — значит снимок подозрительно пуст

mkdir -p "$DEST"
# Витрина — каталог пользователя, а не под root: без sudo туда не дойти.
#
# Создавать надо через `install -d -o dash`, а не через mkdir: скрипт работает
# от root, и mkdir от root оставил бы каталог под root с правами 700 — внутрь
# не смог бы зайти никто, включая владельца. Так и случилось: первая выкладка
# упала с «Отказано в доступе».
install -d -o dash -g dash -m 700 "$STAGE"
TS=$(date +%Y%m%d-%H%M%S)
RAW="$DEST/kladovka-$TS.db"
GZ="$RAW.gz"
ARCHIVE="$DEST/kladovka-$TS.tar.gz"

fail() {
    echo "backup FAIL $TS: $*" >> "$LOG"
    exit 1
}

# Прежний вариант молчал, если базы нет: .backup падал, cp копировал что-то,
# gzip это что-то сжимал, и в списке бэкапов появлялся ещё один файл.
[ -f "$DB" ] || fail "нет базы $DB"

# .backup — единственный способ снять консистентный снимок базы в режиме WAL:
# обычный cp копирует только основной файл, а недавние коммиты могут лежать
# в -wal и в копию не попасть. Проверено: при 202 строках cp-копия содержала 2.
sqlite3 "$DB" ".backup '$RAW'" 2>/dev/null || fail "sqlite3 .backup не отработал"
[ -s "$RAW" ] || fail "снимок пустой"

gzip -f "$RAW" || fail "не сжался снимок"
[ -s "$GZ" ] || fail "сжатый бэкап пуст"

# Проверка: бэкап, который не открывается, хуже отсутствия бэкапа — о нём
# думают, что он есть.
T=$(mktemp /tmp/kladovka-check-XXXXXX.db)
trap 'rm -f "$T"' EXIT
zcat "$GZ" > "$T" 2>/dev/null || fail "сжатый бэкап не распаковывается"

INTEG=$(sqlite3 "$T" "PRAGMA integrity_check;" 2>/dev/null || echo "не прочиталась")
[ "$INTEG" = "ok" ] || fail "integrity_check: $INTEG"

ROWS=$(sqlite3 "$T" "SELECT COUNT(*) FROM items;" 2>/dev/null || echo 0)
if [ "$ROWS" -lt "$THRESHOLD" ]; then
    # Предупреждение, а не ошибка: пустой склад — законное состояние (например,
    # снепшот сняли сразу после импорта). Но сообщить надо, иначе сломанная
    # выгрузка будет выглядеть как «у человека просто мало вещей».
    echo "backup WARN $TS: в снимке $ROWS строк items (порог $THRESHOLD)" >> "$LOG"
fi

# Фотографии: каталога может не быть (никто ничего не загружал) — это не
# поломка. Сам каталог в архив кладём только если он непуст, иначе запись
# будет занимать место ради ничего.
PHOTO_COUNT=0
if [ -d "$PHOTOS" ]; then
    PHOTO_COUNT=$(find "$PHOTOS" -maxdepth 1 -type f | wc -l)
    if [ "$PHOTO_COUNT" -gt 0 ]; then
        tar -czf "$ARCHIVE" -C "$(dirname "$PHOTOS")" "$(basename "$PHOTOS")" 2>/dev/null \
            || fail "не удалось собрать архив с фотографиями"
        [ -s "$ARCHIVE" ] || fail "архив с фотографиями пуст"
        # Проверяем, что архив читается и внутри ожидаемое число файлов.
        # Считаем ТОЛЬКО файлы: tar кладёт ещё и сам каталог «photos/» с
        # завершающим слэшем, и в первом варианте проверки он попадал в счёт,
        # из-за чего исправный архив объявлялся битым. Регулярка требует
        # непустое имя после слэша, поэтому запись каталога отсекается.
        LISTED=$(tar -tzf "$ARCHIVE" 2>/dev/null | grep -c "^photos/[^/][^/]*$" || true)
        [ "$LISTED" -eq "$PHOTO_COUNT" ] || fail "в архиве $LISTED файлов, ожидалось $PHOTO_COUNT"
    fi
fi

# Ссылки переставляются ПОСЛЕ всех проверок: прежняя версия делала это раньше,
# и latest указывал на файл, который ещё не был проверен.
ln -sf "$(basename "$GZ")" "$DEST/latest.db.gz"

# Ссылка на фотографии ставится только когда они действительно есть. Иначе она
# продолжала бы указывать на архив ПРОШЛОГО раза — и человек, восстанавливающий
# по ней, получил бы старые фотографии, решив, что они свежие. Снимок без фото
# честнее, чем ссылка на чужое.
if [ "$PHOTO_COUNT" -gt 0 ]; then
    ln -sf "$(basename "$ARCHIVE")" "$DEST/latest-photos.tar.gz"
    echo "photos=$PHOTO_COUNT" >> "$LOG"
else
    rm -f "$DEST/latest-photos.tar.gz"
    echo "photos=0 (архива нет; прошлая ссылка снята)" >> "$LOG"
fi

# Удаление старых: и .db.gz, и .tar.gz, иначе фотографии копились бы вечно
find "$DEST" \( -name 'kladovka-*.db.gz' -o -name 'kladovka-*.tar.gz' \) -mtime +"$KEEP_DAYS" -delete

# Выкладываем проверенный снимок на витрину. Только после всех проверок выше:
# отдавать наружу имеет смысл то, что уже прошло integrity_check.
#
# `install` вместо `cp`, потому что он выставляет права и владельца за один
# шаг, и копия сразу уходит с правами 600 на пользователя. Прежняя копия
# заменяется одной командой `mv`, и на витрине всегда лежит ровно один файл
# последнего снимка — иначе на машину тянулось бы всё подряд.
install -o dash -g dash -m 600 "$GZ" "$STAGE/.kladovka-new.db.gz"
mv -f "$STAGE/.kladovka-new.db.gz" "$STAGE/latest.db.gz"

if [ "$PHOTO_COUNT" -gt 0 ]; then
    install -o dash -g dash -m 600 "$ARCHIVE" "$STAGE/.kladovka-new-photos.tar.gz"
    mv -f "$STAGE/.kladovka-new-photos.tar.gz" "$STAGE/latest-photos.tar.gz"
else
    # Фотографий нет — снять и ссылку, по той же причине, что и в $DEST:
    # ссылка на прошлый архив выглядела бы как свежие фотографии.
    rm -f "$STAGE/latest-photos.tar.gz"
fi

echo "backup ok $TS: items=$ROWS photos=$PHOTO_COUNT" >> "$LOG"

# Права на кроновые скрипты. Этот скрипт — единственный, кто точно запускается
# каждый день, поэтому дешевле всего чинить права здесь.
#
# Случай был настоящий: у /www/backup/check-kladovka.sh слетел бит исполнения
# (скрипт выложили через scp обычным файлом). Крон при этом НЕ ругается — он
# молча пропускает запуск, ошибка уходит в почту root, а почты на машине нет.
# Итог: два дня подряд монитор не работал, а последняя строка его лога
# продолжала говорить «OK» — выглядело как штатная работа.
#
# Поэтому здесь права не только чинятся, но и починка записывается в лог:
# по логу видно, что скрипт кто-то трогал.
for CRON_SCRIPT in /www/backup/check-kladovka.sh /www/backup/backup-kladovka.sh; do
    if [ -f "$CRON_SCRIPT" ]; then
        BEFORE=$(stat -c '%a' "$CRON_SCRIPT")
        if [ "$BEFORE" != "700" ]; then
            chmod 700 "$CRON_SCRIPT"
            echo "fixed exec bits: $CRON_SCRIPT was $BEFORE, now 700" >> "$LOG"
        fi
    fi
done

# Последняя строка — в stdout, её видно и при ручном запуске, и в логе cron.
echo "backup ok: items=$ROWS photos=$PHOTO_COUNT db=$(basename "$GZ")"