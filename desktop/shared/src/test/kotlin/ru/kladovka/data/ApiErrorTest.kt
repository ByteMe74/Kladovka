package ru.kladovka.data

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Тексты ошибок API.
 *
 * Проверяем в первую очередь 401, потому что это перестало быть экзотикой: выход
 * из аккаунта отзывает вход на сервере по-настоящему, и приложение обязано
 * отличать «сессия отозвана, войдите снова» от «неверный пароль». Оба ответа
 * приходят с кодом 401, поэтому различает их только текст сервера.
 */
class ApiErrorTest {

    private val api = ApiClient()

    @Test
    fun `отозванный вход объясняется словами, а не кодом`() {
        val msg = api.httpMessage(401, """{"error":"Не авторизовано"}""")
        assertTrue(
            msg.contains("отозван") && msg.contains("войдите", ignoreCase = true),
            "должно быть понятно, что вход отозван и надо войти снова, а не «Сервер ответил 401»"
        )
        assertTrue(
            !msg.contains("401"),
            "человеку код ответа ничего не говорит, он в сообщении лишний: $msg"
        )
    }

    @Test
    fun `неверный пароль не выдаётся за отозванную сессию`() {
        val msg = api.httpMessage(401, """{"error":"Неверный логин или пароль"}""")
        assertEquals("Неверный логин или пароль", msg)
    }

    @Test
    fun `текст сервера важнее нашего текста про сессию`() {
        // На 401 с чужим сообщением мы не имеем права подменять его своим:
        // иначе человек увидит «отозван вход», хотя на самом деле ошибка в пароле.
        val msg = api.httpMessage(401, """{"error":"Аккаунт заблокирован"}""")
        assertEquals("Аккаунт заблокирован", msg)
    }

    @Test
    fun `при отсутствии текста сервера остаётся понятная заглушка`() {
        assertEquals("Сервер ответил 500", api.httpMessage(500, ""))
        assertEquals("Сервер ответил 502", api.httpMessage(502, "<html>bad gateway</html>"))
        assertEquals("Недостаточно прав для этого действия", api.httpMessage(403, ""))
    }

    @Test
    fun `сломанный json не роняет разбор ошибки`() {
        // Сервер может вернуть HTML вместо JSON — тогда падать нельзя,
        // иначе вместо внятной ошибки человек получит исключение о разборе.
        val msg = api.httpMessage(401, "не json вовсе")
        assertEquals("Сервер ответил 401", msg)
    }

    @Test
    fun `код ошибки доступен для разбора, а не только текст`() {
        // SyncScreen отличает отозванную сессию по коду: он решает, входить ли
        // заново. Поэтому код обязан быть в исключении, а не только в тексте.
        val e = ApiException(401, "Сессия отозвана")
        assertEquals(401, e.code)
        assertTrue(e is java.io.IOException, "ApiException должен оставаться IOException, его ловят вызовы сети")
    }
}